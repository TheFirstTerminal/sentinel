// mltrain trains Sentinel's ML classifier and writes an evaluation report.
//
//	cd gateway && go run ./cmd/mltrain
//
// It generates labelled data (internal/ml/dataset), trains a logistic
// regression, and tests it on separate data and on evasion variants
// (internal/ml/evasion), next to the WAF rules alone and both combined.
// Output: internal/ml/model.json and ../docs/ml-report.md. Same seeds, same
// result.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"math"
	"math/rand"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"sentinel/gateway/internal/ml"
	"sentinel/gateway/internal/ml/csic"
	"sentinel/gateway/internal/ml/dataset"
	"sentinel/gateway/internal/ml/evasion"
	"sentinel/gateway/internal/waf"
)

const (
	trainN    = 25000 // attacks (and as many normal inputs) to train on
	testN     = 5000
	evasionN  = 4000
	epochs    = 8
	threshold = 0.9 // probability that counts as an attack (ML_THRESHOLD)
)

func main() {
	csicDir := flag.String("csic", "", "folder with the CSIC 2010 dataset (adds real-format web traffic to training and a CSIC test to the report)")
	crsDir := flag.String("crs", "", "OWASP CRS rules/ folder, for the CSIC comparison (optional)")
	flag.Parse()
	start := time.Now()
	train := dataset.Generate(trainN, 1)
	test := dataset.Generate(testN, 2)
	var cs *csicData
	if *csicDir != "" {
		cs = loadCSIC(*csicDir)
		train = append(train, cs.train...)
	}

	vecs := make([]ml.Vector, len(train))
	for i, e := range train {
		vecs[i] = ml.Featurize(e.Text)
	}
	m := fit(vecs, train)
	m.Version = "1"
	m.Trained = fmt.Sprintf("%d examples, %d epochs, seed 1", len(train), epochs)
	if cs != nil {
		m.Trained += fmt.Sprintf(", including %d from CSIC 2010", len(cs.train))
	}

	rules, _ := waf.LoadRules("")
	engine := waf.NewEngine(rules, 5)
	wafHit := func(s string) bool {
		r, _ := http.NewRequest("GET", "/search?q="+url.QueryEscape(s), nil)
		return engine.Inspect(r, nil).Attack
	}
	mlHit := func(s string) bool { p, _ := m.ScoreText(s); return p >= threshold }

	var rep strings.Builder
	fmt.Fprintf(&rep, "# Sentinel ML classifier: evaluation\n\n")
	fmt.Fprintf(&rep, "Generated by `go run ./cmd/mltrain` (%s). Model: logistic regression over hashed character 3-5-grams, words and word pairs (%d slots), trained on %d synthetic examples (half attacks from %d families, half normal input). Threshold: %.2f.\n\n",
		time.Now().Format("2006-01-02"), ml.Dim, len(train), len(dataset.Families()), threshold)
	fmt.Fprintf(&rep, "> The data is generated, not captured from real traffic. The numbers show how the model behaves on fresh data from the same generator and on evasion variants it never saw; real traffic will differ. Run Sentinel with `ML_MODE=detect` on real traffic first and check the log before blocking.\n\n")

	// 1. Fresh test data.
	cm := confusion(test, wafHit, mlHit)
	fmt.Fprintf(&rep, "## 1. Fresh test data (%d attacks, %d normal, different seed)\n\n", testN, testN)
	fmt.Fprintf(&rep, "| | Attacks caught | Normal input wrongly blocked |\n|---|---|---|\n")
	for _, name := range []string{"WAF rules", "ML", "WAF + ML"} {
		c := cm[name]
		fmt.Fprintf(&rep, "| %s | %s | %s |\n", name, pct(c.tp, c.tp+c.fn), pct(c.fp, c.fp+c.tn))
	}

	// Per family.
	fmt.Fprintf(&rep, "\n### Attacks caught per family\n\n| Family | WAF rules | ML | WAF + ML |\n|---|---|---|---|\n")
	fams := map[string][3]int{}
	tot := map[string]int{}
	for _, e := range test {
		if !e.Attack {
			continue
		}
		w, l := wafHit(e.Text), mlHit(e.Text)
		f := fams[e.Family]
		if w {
			f[0]++
		}
		if l {
			f[1]++
		}
		if w || l {
			f[2]++
		}
		fams[e.Family] = f
		tot[e.Family]++
	}
	for _, name := range sortedKeys(tot) {
		f := fams[name]
		fmt.Fprintf(&rep, "| %s | %s | %s | %s |\n", name, pct(f[0], tot[name]), pct(f[1], tot[name]), pct(f[2], tot[name]))
	}

	// False positives on normal input, per kind.
	fmt.Fprintf(&rep, "\n### Normal input wrongly blocked, per kind\n\n| Kind | WAF rules | ML |\n|---|---|---|\n")
	nf := map[string][2]int{}
	nt := map[string]int{}
	var fpExamples []string
	for _, e := range test {
		if e.Attack {
			continue
		}
		w, l := wafHit(e.Text), mlHit(e.Text)
		f := nf[e.Family]
		if w {
			f[0]++
		}
		if l {
			f[1]++
			if len(fpExamples) < 8 {
				fpExamples = append(fpExamples, e.Text)
			}
		}
		nf[e.Family] = f
		nt[e.Family]++
	}
	for _, name := range sortedKeys(nt) {
		fmt.Fprintf(&rep, "| %s | %s | %s |\n", name, pct(nf[name][0], nt[name]), pct(nf[name][1], nt[name]))
	}
	if len(fpExamples) > 0 {
		fmt.Fprintf(&rep, "\nExamples the ML wrongly flagged:\n\n")
		for _, s := range fpExamples {
			fmt.Fprintf(&rep, "- `%s`\n", strings.ReplaceAll(s, "`", "'"))
		}
	}

	// 2. Evasion.
	r := rand.New(rand.NewSource(3))
	var attacks []dataset.Example
	for _, e := range dataset.Generate(evasionN, 4) {
		if e.Attack {
			attacks = append(attacks, e)
		}
	}
	type ev struct{ n, w, l, b int }
	byMut := map[string]*ev{}
	all := &ev{}
	var bothMissed []string
	for _, e := range attacks {
		s, used := evasion.Apply(r, e.Text)
		w, l := wafHit(s), mlHit(s)
		for _, u := range append(used, "(all)") {
			x := byMut[u]
			if x == nil {
				x = &ev{}
				byMut[u] = x
			}
			if u == "(all)" {
				x = all
			}
			x.n++
			if w {
				x.w++
			}
			if l {
				x.l++
			}
			if w || l {
				x.b++
			}
		}
		if !w && !l && len(bothMissed) < 8 {
			bothMissed = append(bothMissed, s)
		}
	}
	fmt.Fprintf(&rep, "\n## 2. Evasion test (%d attacks, each rewritten with 1-3 evasion techniques)\n\n", all.n)
	fmt.Fprintf(&rep, "| Technique | Attacks | WAF rules | ML | WAF + ML |\n|---|---|---|---|---|\n")
	fmt.Fprintf(&rep, "| **all** | %d | %s | %s | %s |\n", all.n, pct(all.w, all.n), pct(all.l, all.n), pct(all.b, all.n))
	var names []string
	for k := range byMut {
		if k != "(all)" {
			names = append(names, k)
		}
	}
	sort.Strings(names)
	for _, k := range names {
		x := byMut[k]
		fmt.Fprintf(&rep, "| %s | %d | %s | %s | %s |\n", k, x.n, pct(x.w, x.n), pct(x.l, x.n), pct(x.b, x.n))
	}
	if len(bothMissed) > 0 {
		fmt.Fprintf(&rep, "\nExamples both missed (ideas for new rules and training data):\n\n")
		for _, s := range bothMissed {
			fmt.Fprintf(&rep, "- `%s`\n", strings.ReplaceAll(cut(s, 120), "`", "'"))
		}
	}

	// 3. Explanations.
	fmt.Fprintf(&rep, "\n## 3. Example explanations\n\n| Input | ML score | Strongest reasons |\n|---|---|---|\n")
	for _, s := range []string{"1' AND extractvalue(1,concat(0x7e,(SELECT user())))-- -", "<details open ontoggle=confirm(1)>", "x'||pg_sleep(10)--", "rock 'n' roll t-shirt", "Please select a different size"} {
		e := m.Explain(s, 3)
		fmt.Fprintf(&rep, "| `%s` | %.2f | %s |\n", strings.ReplaceAll(s, "|", "\\|"), e.Probability, strings.ReplaceAll(e.Summary(), "|", "\\|"))
	}
	if cs != nil {
		fmt.Fprintf(&rep, "\n## 4. CSIC 2010: real-format web traffic\n\n")
		fmt.Fprintf(&rep, "The [CSIC 2010 HTTP dataset](https://www.tic.itefi.csic.es/dataset/) (Spanish National Research Council) is traffic to a web shop: normal requests and %d attacks (SQL injection, XSS, buffer overflow, CRLF, SSI, file disclosure, parameter tampering). "+
			"The model was trained on its %d normal training requests and on a random 70%% of the attacks (seed 11). The test below uses only data it never saw: the %d normal *test* requests and the other 30%% of the attacks (%d). "+
			"In the attacks used for training, only values that never occur in normal traffic for that field were labelled as attacks: the other fields of those requests are ordinary.\n\n",
			cs.attacksTotal, cs.normalTrain, len(cs.normalTest), len(cs.attackTest))
		fmt.Fprintf(&rep, "%s\n", csic.Evaluate(cs.normalTest, cs.attackTest, m, *crsDir))
		fmt.Fprintf(&rep, "Many CSIC attacks are parameter tampering (an impossible value in an ordinary field) rather than attack syntax, so rules alone, which look for attack syntax, catch fewer of them. Request-level decisions: a request counts as caught if any check stops it.\n")
	}
	fmt.Fprintf(&rep, "\nTraining took %s.\n", time.Since(start).Round(time.Second))

	// Write the model with 4 decimals (smaller file, same decisions).
	for i, w := range m.Weights {
		m.Weights[i] = math.Round(w*1e4) / 1e4
	}
	m.Bias = math.Round(m.Bias*1e4) / 1e4
	b, _ := json.Marshal(m)
	must(os.WriteFile("internal/ml/model.json", b, 0o644))
	must(os.WriteFile("../docs/ml-report.md", []byte(rep.String()), 0o644))
	fmt.Print(rep.String())
}

// fit trains logistic regression with AdaGrad and a little L2.
func fit(x []ml.Vector, data []dataset.Example) *ml.Model {
	w := make([]float64, ml.Dim)
	g2 := make([]float64, ml.Dim)
	var b, bg2 float64
	const lr, l2 = 0.5, 1e-6
	order := rand.New(rand.NewSource(7)).Perm(len(x))
	for ep := 0; ep < epochs; ep++ {
		for _, n := range order {
			v := x[n]
			z := b
			for k, i := range v.Idx {
				z += w[i] * v.Val[k]
			}
			p := 1 / (1 + math.Exp(-z))
			y := 0.0
			if data[n].Attack {
				y = 1
			}
			grad := p - y
			for k, i := range v.Idx {
				gi := grad*v.Val[k] + l2*w[i]
				g2[i] += gi * gi
				w[i] -= lr * gi / (math.Sqrt(g2[i]) + 1e-8)
			}
			bg2 += grad * grad
			b -= lr * grad / (math.Sqrt(bg2) + 1e-8)
		}
	}
	return &ml.Model{Bias: b, Weights: w}
}

type csicData struct {
	train                  []dataset.Example
	normalTest, attackTest []csic.Request
	normalTrain            int
	attacksTotal           int
}

// loadCSIC builds training examples from CSIC 2010 and keeps a test split.
func loadCSIC(dir string) *csicData {
	normalTrain, err := csic.Load(filepath.Join(dir, "normalTrafficTraining.txt"), false)
	must(err)
	normalTest, err := csic.Load(filepath.Join(dir, "normalTrafficTest.txt"), false)
	must(err)
	attacks, err := csic.Load(filepath.Join(dir, "anomalousTrafficTest.txt"), true)
	must(err)
	d := &csicData{normalTest: normalTest, normalTrain: len(normalTrain), attacksTotal: len(attacks)}

	// Normal: every distinct value of every field.
	seen := map[string]map[string]bool{}
	norm := map[string]bool{}
	for _, q := range normalTrain {
		for _, in := range csic.Values(q) {
			k := strings.ToLower(in.Field)
			if seen[k] == nil {
				seen[k] = map[string]bool{}
			}
			seen[k][in.Value] = true
			norm[in.Value] = true
		}
	}
	for v := range norm {
		d.train = append(d.train, dataset.Example{Text: v, Attack: false, Family: "csic-normal"})
	}
	// Attacks: a fixed 70% for training, the rest held out for testing.
	order := rand.New(rand.NewSource(11)).Perm(len(attacks))
	cut := len(attacks) * 7 / 10
	bad := map[string]bool{}
	for _, i := range order[:cut] {
		for _, in := range csic.Values(attacks[i]) {
			if !seen[strings.ToLower(in.Field)][in.Value] && !norm[in.Value] {
				bad[in.Value] = true
			}
		}
	}
	for v := range bad {
		d.train = append(d.train, dataset.Example{Text: v, Attack: true, Family: "csic-attack"})
	}
	for _, i := range order[cut:] {
		d.attackTest = append(d.attackTest, attacks[i])
	}
	sort.Slice(d.train, func(i, j int) bool { return d.train[i].Text < d.train[j].Text }) // same order every run
	fmt.Fprintf(os.Stderr, "CSIC: %d normal values, %d attack values for training; test: %d normal, %d attacks\n", len(norm), len(bad), len(normalTest), len(d.attackTest))
	return d
}

type counts struct{ tp, fn, fp, tn int }

func confusion(data []dataset.Example, wafHit, mlHit func(string) bool) map[string]*counts {
	out := map[string]*counts{"WAF rules": {}, "ML": {}, "WAF + ML": {}}
	for _, e := range data {
		w, l := wafHit(e.Text), mlHit(e.Text)
		for name, hit := range map[string]bool{"WAF rules": w, "ML": l, "WAF + ML": w || l} {
			c := out[name]
			switch {
			case e.Attack && hit:
				c.tp++
			case e.Attack:
				c.fn++
			case hit:
				c.fp++
			default:
				c.tn++
			}
		}
	}
	return out
}

func pct(a, b int) string {
	if b == 0 {
		return "–"
	}
	return fmt.Sprintf("%.1f%% (%d/%d)", 100*float64(a)/float64(b), a, b)
}

func sortedKeys(m map[string]int) []string {
	var k []string
	for x := range m {
		k = append(k, x)
	}
	sort.Strings(k)
	return k
}

func cut(s string, n int) string {
	if len(s) > n {
		return s[:n] + "..."
	}
	return s
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
